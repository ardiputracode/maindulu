test('an account API outage is visible and recoverable without affecting the guest catalog', async ({ page }) => {
  await page.route('**/api/auth/session', route => route.abort())
  const dialog = await openLogin(page)
  await expect(dialog.getByRole('alert')).toContainText('Informasi akun belum dapat dimuat')
  await page.unroute('**/api/auth/session')
  await dialog.getByRole('button', { name: 'Periksa akun lagi' }).click()
  await expect(dialog.getByLabel('Username', { exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('button', { name: 'Mainkan Jalan Pulang', exact: true })).toBeVisible()
})

test('recovery resets credentials, shows a new code once and revokes another browser session', async ({ page, browser, baseURL }) => {
  const username = uniqueName()
  const { code } = await register(page, username)
  await finishRegistration(page)
  const other = await browser.newContext({ baseURL })
  try {
    const second = await other.newPage()
    await login(second, username)
    await expect(second.getByRole('dialog')).toHaveCount(0)
    await page.getByRole('button', { name: `Akun ${username}`, exact: true }).click()
    await page.getByRole('button', { name: 'Keluar akun', exact: true }).click()
    const dialog = await openLogin(page)
    await dialog.getByRole('button', { name: 'Lupa password?', exact: true }).click()
    await expect(dialog).toContainText('hubungi pemilik/pengelola komputer server')
    await dialog.getByLabel('Username', { exact: true }).fill(' ' + username.toUpperCase() + ' ')
    await dialog.getByLabel('Kode pemulihan', { exact: true }).fill('00'.repeat(32))
    await dialog.getByLabel('Password baru', { exact: true }).fill(newPassword)
    await dialog.getByLabel('Konfirmasi password baru', { exact: true }).fill(newPassword)
    await dialog.getByRole('button', { name: 'Reset password', exact: true }).click()
    await expect(dialog.getByRole('alert')).toHaveText('Username atau kode pemulihan tidak sesuai.')
    await dialog.getByLabel('Kode pemulihan', { exact: true }).fill(code.toLowerCase())
    await dialog.getByRole('button', { name: 'Reset password', exact: true }).click()
    await expect(dialog.getByRole('status')).toContainText('Semua sesi lama dicabut')
    const nextCode = await dialog.getByLabel('Kode pemulihan', { exact: true }).inputValue()
    expect(nextCode).not.toBe(code)
    await expect(dialog.getByRole('button', { name: 'Selesai', exact: true })).toBeDisabled()
    await page.keyboard.press('Escape')
    await expect(dialog).toBeVisible()
    await finishRegistration(page)
    await expect(page.getByRole('button', { name: 'Masuk ke akun', exact: true })).toBeVisible()
    await second.reload()
    await expect(second.getByRole('button', { name: 'Masuk ke akun', exact: true })).toBeVisible()
    await login(second, username)
    await expect(second.getByRole('alert')).toHaveText('Username atau password tidak sesuai.')
    await second.getByLabel('Password', { exact: true }).fill(newPassword)
    await second.getByRole('button', { name: 'Masuk', exact: true }).click()
    await expect(second.getByRole('button', { name: `Akun ${username}`, exact: true })).toBeVisible()
    const stored = await page.evaluate(() => JSON.stringify({ local: { ...localStorage }, session: { ...sessionStorage } }))
    for (const secret of [code, nextCode, password, newPassword]) expect(stored).not.toContain(secret)
    expect(page.url()).not.toContain(code)
    expect(page.url()).not.toContain(newPassword)
  } finally { await other.close() }
})


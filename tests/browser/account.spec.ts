test('lost recovery response can be handled by login with the new password and reissuing the unseen code', async ({ page }) => {
  const username = uniqueName()
  const { code } = await register(page, username)
  await finishRegistration(page)
  await page.getByRole('button', { name: `Akun ${username}`, exact: true }).click()
  await page.getByRole('button', { name: 'Keluar akun', exact: true }).click()
  const dialog = await openLogin(page)
  await dialog.getByRole('button', { name: 'Lupa password?', exact: true }).click()
  await dialog.getByLabel('Username', { exact: true }).fill(username)
  await dialog.getByLabel('Kode pemulihan', { exact: true }).fill(code)
  await dialog.getByLabel('Password baru', { exact: true }).fill(newPassword)
  await dialog.getByLabel('Konfirmasi password baru', { exact: true }).fill(newPassword)
  await page.route('**/api/auth/recover', async route => {
    const response = await route.fetch()
    expect(response.status()).toBe(200)
    await route.abort()
  })
  await dialog.getByRole('button', { name: 'Reset password', exact: true }).click()
  await expect(dialog.getByRole('alert')).toContainText('Koneksi akun terputus')
  await expect(dialog).toContainText('coba masuk memakai password baru')
  await dialog.getByRole('button', { name: 'Kembali ke masuk', exact: true }).click()
  await dialog.getByLabel('Password', { exact: true }).fill(newPassword)
  await dialog.getByRole('button', { name: 'Masuk', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  await page.getByRole('button', { name: `Akun ${username}`, exact: true }).click()
  await dialog.getByRole('button', { name: 'Terbitkan ulang kode', exact: true }).click()
  await dialog.getByLabel('Password saat ini', { exact: true }).fill(newPassword)
  await dialog.getByRole('button', { name: 'Buat kode baru', exact: true }).click()
  await expect(dialog.getByRole('heading')).toHaveText('Simpan kode pemulihanmu.')
  await finishRegistration(page)
})
